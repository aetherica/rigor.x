"""Copy the RIGOR-X engine modules and data the Worker needs into src/.

The Worker bundles everything under src/. Only the modules on the plugin path
are copied, with a minimal package __init__, so modules that need sqlite3,
threads or network clients (CLI, standalone agent runtime) are not loaded.
"""
from __future__ import annotations

import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCE = REPO / "src" / "rigorx"
TARGET = HERE / "src" / "rigorx"
MODULES = [
    "adaptive_router.py",
    "pipeline.py",
    "run_store.py",
    "host_engine.py",
    "slash_commands.py",
    "do_store.py",
    "engine_rpc.py",
    "mcp_server.py",
]
CATALOG = REPO / "library" / "slash-commands" / "commands.json"


def main() -> None:
    version = next(
        line.split("=", 1)[1].strip().strip('"')
        for line in (SOURCE / "__init__.py").read_text(encoding="utf-8").splitlines()
        if line.startswith("__version__")
    )
    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)
    (TARGET / "__init__.py").write_text(
        f'"""RIGOR-X engine subset for Cloudflare Workers (generated by sync_engine.py)."""\n\n__version__ = "{version}"\n',
        encoding="utf-8",
    )
    for name in MODULES:
        shutil.copy2(SOURCE / name, TARGET / name)
    data = HERE / "src" / "data"
    data.mkdir(parents=True, exist_ok=True)
    shutil.copy2(CATALOG, data / "commands.json")
    print(f"Synced RIGOR-X {version}: {len(MODULES)} modules and the slash-command catalogue into {HERE / 'src'}")


if __name__ == "__main__":
    main()
